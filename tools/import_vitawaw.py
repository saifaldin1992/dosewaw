"""One-off import of the vitamin calculators from a VITAWAW checkout.
Usage: python3 tools/import_vitawaw.py /path/to/vitawaw-main
- content/vitamins/src/: the original files (medical logic unchanged: calculators.js, data.js, i18n.js, util.js, validation.js)
- content/vitamins/form.html: the patient form of the calculators (fields keep their ids)
- js/rules/vitamins.js: one generated file that runs the original calculators in their own scope (VIT.run)
Re-run after editing content/vitamins/src/ with:  python3 tools/import_vitawaw.py --rebuild"""
import os, re, shutil, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src_dir = os.path.join(root, 'content', 'vitamins', 'src')
FILES = ['i18n.js', 'util.js', 'validation.js', 'data.js', 'calculators.js']
if sys.argv[1] != '--rebuild':
    v = sys.argv[1]
    os.makedirs(src_dir, exist_ok=True)
    for f in FILES: shutil.copy(os.path.join(v, 'js', f), os.path.join(src_dir, f))
    html = open(os.path.join(v, 'index.html'), encoding='utf-8').read()
    a = html.index('<section id="s-data">'); a = html.index('<div class="grid">', a)
    b = html.index('<p class="privacy">', a)
    open(os.path.join(root, 'content', 'vitamins', 'form.html'), 'w', encoding='utf-8').write(html[a:b].strip() + '\n')
    names = re.findall(r'<button data-k="(\w+)"[^>]*><span data-t="(n_\w+)">[^<]*</span><small data-t="(h_\w+)">', html)
    open(os.path.join(root, 'content', 'vitamins', 'keys.txt'), 'w').write('\n'.join(' '.join(n) for n in names) + '\n')
form = open(os.path.join(root, 'content', 'vitamins', 'form.html'), encoding='utf-8').read()
keys = [l.split() for l in open(os.path.join(root, 'content', 'vitamins', 'keys.txt')).read().split('\n') if l.strip()]
body = '\n'.join(f'/* ---- {f} ---- */\n' + open(os.path.join(src_dir, f), encoding='utf-8').read() for f in FILES)
js_keys = ','.join(f"['{k}','{n}','{h}']" for k, n, h in keys)
out = f"""/* DOSEWAW · js/rules/vitamins.js — GENERATED by tools/import_vitawaw.py; do not edit by hand.
   The VITAWAW calculators (content/vitamins/src/, medical logic unchanged) run here in their own scope.
   VIT.run(key, lang) reads the form (content/vitamins/form.html) and returns {{r}} (the result object) or {{empty}}. */
const VIT=(function(){{
const CFG={{text:{{}}}};
{body}
/* ---- DOSEWAW bridge: the calculators call render(r) or emptyState(); keep the result instead of drawing it ---- */
let OUT=null;
function render(r){{OUT={{r}}}}
/* helpers the calculators take from other VITAWAW files: teen() from render.js; conv() and gz() fill the D-drops and Ganzoni
   tools after a result (tools are not part of DOSEWAW yet), so they do nothing here and the form carries their hidden fields */
const teen=a=>a>=14&&a<=18;
function conv(){{}}
function gz(){{}}
function emptyState(missing,bad){{OUT={{empty:true,missing,bad}}}}
const FN={{d:fD,b12:fB12,fol:fFol,fe:fFe,ca:fCa,mg:fMg,c:fC,zn:fZn,preg:fPreg,inf:fInf,vac:fVA,bar:fBar,thi:fThi}};
const KEYS=[{js_keys}];
function run(k,lang){{LANG=lang;K=k;OUT=null;FN[k]();return OUT}}
function setLang(l){{LANG=l}}
const FORM={form!r}+'<div hidden><input id="iu"><input id="gw"><input id="gha"></div>';
return {{run,setLang,KEYS,FORM,I18N,T,REFS,REFGROUP:DEF_REFGROUP,INTER:DEF_INTER,showFor:k=>{{K=k;showFor()}},fmt}};
}})();
if(typeof module!=='undefined')module.exports={{VIT}};
"""
open(os.path.join(root, 'js', 'rules', 'vitamins.js'), 'w', encoding='utf-8').write(out)
print('vitamins.js', len(out), 'bytes,', len(keys), 'calculators')
